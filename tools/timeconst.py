#!/usr/bin/env python3
"""Generate include/generated/timeconst.h, the way kernel/time/timeconst.bc does.

The build normally pipes "HZ" plus the .bc script through GNU bc.  GNU bc's
read() is an extension busybox bc does not have, and bc is not installed here,
so this reproduces the same integer maths.
"""
import sys


def gcd(a, b):
    while b:
        a, b = b, a % b
    return a


def fmul(b, n, d):
    return (2 ** b * n + d - 1) // d


def fadj(b, n, d):
    d = d // gcd(n, d)
    return 2 ** b * (d - 1) // d


def fmuls(b, n, d):
    s = 0
    while True:
        if fmul(s, n, d) >= 2 ** (b - 1):
            return s
        s += 1


def main():
    hz = int(sys.argv[1]) if len(sys.argv) > 1 else 250
    o = []
    p = o.append
    p("/* Automatically generated by kernel/time/timeconst.bc */")
    p("/* Time conversion constants for HZ == %d */" % hz)
    p("")
    p("#ifndef KERNEL_TIMECONST_H")
    p("#define KERNEL_TIMECONST_H")
    p("")
    p("#include <linux/param.h>")
    p("#include <linux/types.h>")
    p("")
    p("#if HZ != %d" % hz)
    p('#error "include/generated/timeconst.h has the wrong HZ value!"')
    p("#endif")
    p("")
    if hz < 2:
        p("#error Totally bogus HZ value!")
    else:
        s = fmuls(32, 1000, hz)
        p("#define HZ_TO_MSEC_MUL32	U64_C(0x%x)" % fmul(s, 1000, hz))
        p("#define HZ_TO_MSEC_ADJ32	U64_C(0x%x)" % fadj(s, 1000, hz))
        p("#define HZ_TO_MSEC_SHR32	%d" % s)
        s = fmuls(32, hz, 1000)
        p("#define MSEC_TO_HZ_MUL32	U64_C(0x%x)" % fmul(s, hz, 1000))
        p("#define MSEC_TO_HZ_ADJ32	U64_C(0x%x)" % fadj(s, hz, 1000))
        p("#define MSEC_TO_HZ_SHR32	%d" % s)
        cd = gcd(hz, 1000)
        p("#define HZ_TO_MSEC_NUM		%d" % (1000 // cd))
        p("#define HZ_TO_MSEC_DEN		%d" % (hz // cd))
        p("#define MSEC_TO_HZ_NUM		%d" % (hz // cd))
        p("#define MSEC_TO_HZ_DEN		%d" % (1000 // cd))
        p("")
        s = fmuls(32, 1000000, hz)
        p("#define HZ_TO_USEC_MUL32	U64_C(0x%x)" % fmul(s, 1000000, hz))
        p("#define HZ_TO_USEC_ADJ32	U64_C(0x%x)" % fadj(s, 1000000, hz))
        p("#define HZ_TO_USEC_SHR32	%d" % s)
        s = fmuls(32, hz, 1000000)
        p("#define USEC_TO_HZ_MUL32	U64_C(0x%x)" % fmul(s, hz, 1000000))
        p("#define USEC_TO_HZ_ADJ32	U64_C(0x%x)" % fadj(s, hz, 1000000))
        p("#define USEC_TO_HZ_SHR32	%d" % s)
        cd = gcd(hz, 1000000)
        p("#define HZ_TO_USEC_NUM		%d" % (1000000 // cd))
        p("#define HZ_TO_USEC_DEN		%d" % (hz // cd))
        p("#define USEC_TO_HZ_NUM		%d" % (hz // cd))
        p("#define USEC_TO_HZ_DEN		%d" % (1000000 // cd))
        p("")
        cd = gcd(hz, 1000000000)
        p("#define HZ_TO_NSEC_NUM		%d" % (1000000000 // cd))
        p("#define HZ_TO_NSEC_DEN		%d" % (hz // cd))
        p("#define NSEC_TO_HZ_NUM		%d" % (hz // cd))
        p("#define NSEC_TO_HZ_DEN		%d" % (1000000000 // cd))
        p("")
    p("#endif /* KERNEL_TIMECONST_H */")
    print("\n".join(o))


if __name__ == "__main__":
    main()
